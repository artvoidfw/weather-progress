export function getWeatherCondition(code, lang = 'en') {
  if (weatherDescriptions[code] && weatherDescriptions[code][lang]) {
    return weatherDescriptions[code][lang];
  }
  if (weatherDescriptions[code] && weatherDescriptions[code].en) {
    return weatherDescriptions[code].en;
  }
  return lang === 'az' ? 'Aydın' : 'Clear';
}

export function getWeatherIconType(code, isDay = 1) {
  if (code === 0 || code === 1) {
    return isDay ? 'sun' : 'moon';
  }
  if (code === 2) {
    return isDay ? 'cloud-sun' : 'cloud-moon';
  }
  if (code === 3) {
    return 'cloud';
  }
  if (code === 45 || code === 48) {
    return 'fog';
  }
  if ([51, 53, 55, 61, 63, 80].includes(code)) {
    return 'rain-light';
  }
  if ([65, 81, 82].includes(code)) {
    return 'rain-heavy';
  }
  if ([71, 73, 75, 77, 85, 86].includes(code)) {
    return 'snow';
  }
  if ([95, 96, 99].includes(code)) {
    return 'thunder';
  }
  return isDay ? 'sun' : 'moon';
}
